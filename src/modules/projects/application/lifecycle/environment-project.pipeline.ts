import type { DeploymentProvisioningResult } from '#kernel/ports/deployment-runtime.port';
import { targetsForEnvironment } from '../../domain/environment-deployment-targets.policy';
import type { ProvisioningSlot } from '../../domain/deployment-provisioning.policy';
import type {
  CreateProjectDto,
  DeploymentProvisioningRequestDto,
} from '../../api/dto/create-project.dto';
import type { ProjectEnvironmentRecord } from '../../domain/project-environment.policy';
import type { ProvisionedProjectRow } from '../../infrastructure/projects.repository';
import type { StagedWorkflowFile } from '../workflows/index';
import type {
  StagedEnvironmentTarget,
  StagedWorkflowEnvironment,
} from '../workflows/staged-workflow.builder';
import type {
  ProjectProvisioningSupport,
  WorkflowBundleOptions,
} from './project-provisioning.support';
import { configureReleaseSigning } from './release-signing.provisioning';

/**
 * The environments a pipeline is first generated with, before the project row
 * (and so the real environment IDs) exists. Only the file list and workflow
 * path of that first bundle are used; the real pipeline is generated by
 * completeEnvironmentPipeline once the targets exist.
 */
export function placeholderWorkflowEnvironments(
  environments: CreateProjectDto['environments'],
): Pick<WorkflowBundleOptions, 'environments' | 'environmentTargets'> {
  if (!environments) return {};
  return {
    environments: environments.map((environment, position) => ({
      id: environment.slug,
      slug: environment.slug,
      sourceBranch: environment.sourceBranch,
      position,
      role: environment.role,
    })),
    environmentTargets: [],
  };
}

/** The workflow settings of one repository's environment pipeline. */
export type EnvironmentPipelineWorkflow = Omit<
  WorkflowBundleOptions,
  'environments' | 'environmentTargets'
>;

export interface EnvironmentPipelineInput {
  userId: string;
  row: ProvisionedProjectRow;
  provisioningToken: string;
  ownerLogin: string;
  repoName: string;
  repoFullName: string;
  /** Every creation target; only the ones for `slots` are provisioned here. */
  deploymentProvisioning: DeploymentProvisioningRequestDto | undefined;
  /** The slots this repository deploys: all of a single repository's, one half of a pair. */
  slots: ProvisioningSlot[];
  /**
   * One half of a pair: only the targets of `slots` belong to this
   * repository, release signing included. A single repository owns every
   * creation target.
   */
  ownSlotTargetsOnly?: boolean;
  workflow: EnvironmentPipelineWorkflow;
}

export interface EnvironmentPipelineResult {
  environments: ProjectEnvironmentRecord[];
  /** Every distinct source branch, in environment order. */
  branches: string[];
  workflowFiles: StagedWorkflowFile[];
  /** The pipeline commit on the first environment's branch. */
  commit: { commitSha: string; commitUrl: string | null } | undefined;
  /** Each environment's provisioning result, in environment order. */
  perEnvironment: Array<{
    environment: ProjectEnvironmentRecord;
    result: DeploymentProvisioningResult;
  }>;
  /** All targets of every environment, with one overall status. */
  deploymentProvisioning: DeploymentProvisioningResult;
  /** Set when releases from this repository cannot be signed yet. */
  releaseSigningWarning: string | undefined;
}

/**
 * Give one repository its environment pipeline, once the repository, project
 * row, environments and CI secrets exist.
 *
 * The pipeline names real environment and target IDs, so it is generated
 * last: configure release signing (before any workflow exists, so the first
 * release finds its key), create each distinct source branch, provision one
 * target per environment and slot (each through the environment-aware target
 * path, which also provisions and protects its GitHub Environment), generate
 * the pipeline and push it to every source branch, protect every branch except
 * the first environment's, and record the commit on the row.
 *
 * Runs once per repository: a single-repository project with all its slots,
 * each half of a two-repository project with its own slot.
 */
export async function completeEnvironmentPipeline(
  support: ProjectProvisioningSupport,
  input: EnvironmentPipelineInput,
): Promise<EnvironmentPipelineResult> {
  const { row, provisioningToken, ownerLogin, repoName } = input;
  const requested = input.deploymentProvisioning?.targets ?? [];
  const slotTargets = input.ownSlotTargetsOnly
    ? requested.filter((target) => input.slots.includes(target.slot))
    : requested;
  // Any host-delivered target in any environment consumes the release this
  // repository signs, so every one of its targets counts.
  const releaseSigningWarning = await configureReleaseSigning(support, {
    accessToken: provisioningToken,
    owner: ownerLogin,
    repo: repoName,
    targets: slotTargets,
  });

  const environments = await support.projectsRepository.listProjectEnvironments(
    row.id,
  );
  const first = environments[0];
  if (!first) {
    throw new UnprocessableEntityException(
      'The project environments were not stored.',
    );
  }
  const branches = [
    ...new Set(environments.map(({ sourceBranch }) => sourceBranch)),
  ];

  for (const branch of branches.filter((name) => name !== 'main')) {
    await support.githubService.createBranch(
      provisioningToken,
      ownerLogin,
      repoName,
      branch,
      'main',
    );
  }

  const environmentTargets: StagedEnvironmentTarget[] = [];
  const perEnvironment: EnvironmentPipelineResult['perEnvironment'] = [];
  for (const environment of environments) {
    const request = input.deploymentProvisioning
      ? {
          ...input.deploymentProvisioning,
          targets: targetsForEnvironment(slotTargets, environment.slug).map(
            (target) => ({
              ...target,
              environmentId: environment.id,
              branchName: environment.sourceBranch,
              ...(target.projectName
                ? { projectName: target.projectName + '-' + environment.slug }
                : {}),
            }),
          ),
        }
      : undefined;
    const result = await support.provisionDeploymentTargets({
      projectId: row.id,
      userId: input.userId,
      repoFullName: input.repoFullName,
      githubAccessToken: provisioningToken,
      request,
      slots: input.slots,
    });
    perEnvironment.push({ environment, result });
    for (const target of result.targets) {
      if (target.status !== 'failed' && target.deploymentTargetId) {
        environmentTargets.push({
          environmentId: environment.id,
          slot: target.slot,
          targetId: target.deploymentTargetId,
          provider: target.provider,
        });
      }
    }
  }

  const { workflowFiles } = await support.buildWorkflowBundle({
    ...input.workflow,
    environments: environments.map(
      (environment): StagedWorkflowEnvironment => ({
        id: environment.id,
        slug: environment.slug,
        sourceBranch: environment.sourceBranch,
        position: environment.position,
        role: environment.role,
      }),
    ),
    environmentTargets,
  });

  let commit: EnvironmentPipelineResult['commit'];
  for (const branch of branches) {
    const pushed = await support.pushWorkflowFiles(
      provisioningToken,
      ownerLogin,
      repoName,
      workflowFiles,
      branch,
    );
    if (branch === first.sourceBranch) commit = pushed;
  }
  // The first environment's branch is where developers push; every later
  // environment's branch is protected, and main always is.
  await support.protectPipelineBranches({
    token: provisioningToken,
    owner: ownerLogin,
    repo: repoName,
    userId: input.userId,
    projectId: row.id,
    workspaceId: row.workspace_id ?? null,
    branches: [
      ...new Set([
        ...branches.filter((name) => name !== first.sourceBranch),
        'main',
      ]),
    ],
  });

  await support.projectsRepository.updateStatus(
    row.id,
    'provisioned',
    commit?.commitSha,
    commit?.commitUrl,
  );

  return {
    environments,
    branches,
    workflowFiles,
    commit,
    perEnvironment,
    deploymentProvisioning: combineEnvironmentResults(
      perEnvironment.map(({ result }) => result),
    ),
    releaseSigningWarning,
  };
}

/**
 * Every environment's targets with one status: skipped with none, failed when
 * all failed, partial when some failed, otherwise the first real status.
 */
export function combineEnvironmentResults(
  results: readonly DeploymentProvisioningResult[],
): DeploymentProvisioningResult {
  const targets = results.flatMap(({ targets: created }) => created);
  return {
    status:
      targets.length === 0
        ? 'skipped'
        : targets.every(({ status }) => status === 'failed')
          ? 'failed'
          : targets.some(({ status }) => status === 'failed')
            ? 'partial'
            : (results.find(({ status }) => status !== 'skipped')?.status ??
              'skipped'),
    targets,
  };
}

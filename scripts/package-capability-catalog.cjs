#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { loadSource, validateSource } = require('./lib/composition-source.cjs');
const {
  CANONICAL_PACKAGE_FILES,
  PACKAGE_NAME,
  PROVENANCE_FILE,
  createProvenance,
} = require('./lib/capability-package-provenance.cjs');

const ROOT = path.resolve(__dirname, '..');
const PACKAGE_DIR = path.join(ROOT, 'packages', 'capability-catalog');
const DEFAULT_VERSION = '0.2.0';
const EDITIONS = ['saas', 'edu', 'enterprise'];

function packageVersion() {
  const packageJson = path.join(PACKAGE_DIR, 'package.json');
  if (!fs.existsSync(packageJson)) return DEFAULT_VERSION;
  return JSON.parse(fs.readFileSync(packageJson, 'utf8')).version ?? DEFAULT_VERSION;
}

function publicCatalog(capabilities, manifests) {
  const editionsByKey = new Map(
    EDITIONS.map((edition) => [
      edition,
      new Set(manifests[edition]?.capabilities ?? []),
    ]),
  );

  return capabilities.map((capability) => ({
    key: capability.key,
    context: capability.context,
    description: capability.description,
    maturity: capability.maturity,
    configuration: capability.configuration,
    configurationFlags: [...capability.configurationFlags],
    editions: EDITIONS.filter((edition) => editionsByKey.get(edition).has(capability.key)),
    requires: [...capability.requires],
    surface: {
      apiField: capability.surface.apiField,
      viewFlag: capability.surface.viewFlag,
      domains: [...capability.surface.domains],
      routes: [...capability.surface.routes],
      featureBarrels: [...capability.surface.featureBarrels],
      artifactSymbols: [...(capability.surface.artifactSymbols || [])],
    },
  }));
}

function publicManifests(manifests) {
  return Object.fromEntries(
    EDITIONS.map((edition) => [edition, [...(manifests[edition]?.capabilities ?? [])]]),
  );
}

function declaration(catalog) {
  const keyUnion = catalog
    .map((record) => `  | ${JSON.stringify(record.key)}`)
    .join('\n');
  return `// Generated from src/kernel/composition/catalog.source.json.
// Package integrity is recorded in provenance.json; do not edit this file by hand.
export type Edition = "saas" | "edu" | "enterprise";
export type CapabilityMaturity = "stable" | "limited" | "not-implemented";
export type CapabilityKey =
${keyUnion};

export interface CapabilitySurface {
  readonly apiField: string | null;
  readonly viewFlag: string | null;
  readonly domains: readonly string[];
  readonly routes: readonly string[];
  readonly featureBarrels: readonly string[];
  readonly artifactSymbols: readonly string[];
}

export interface CapabilityCatalogRecord {
  readonly key: CapabilityKey;
  readonly context: string;
  readonly description: string;
  readonly maturity: CapabilityMaturity;
  readonly configuration: string;
  readonly configurationFlags: readonly string[];
  readonly editions: readonly Edition[];
  readonly requires: readonly CapabilityKey[];
  readonly surface: CapabilitySurface;
}

export type CapabilityManifest = readonly CapabilityKey[];

export interface CapabilityCatalogPackage {
  readonly version: string;
  readonly catalog: readonly CapabilityCatalogRecord[];
  readonly manifests: Readonly<Record<Edition, CapabilityManifest>>;
}

export const version: string;
export const catalog: readonly CapabilityCatalogRecord[];
export const manifests: Readonly<Record<Edition, CapabilityManifest>>;
`;
}

function buildPackage() {
  const source = loadSource();
  const sourceErrors = validateSource(source);
  if (sourceErrors.length > 0) {
    throw new Error(`Composition source is invalid: ${sourceErrors.join('; ')}`);
  }
  const capabilities = source.capabilities;
  const manifests = Object.fromEntries(
    EDITIONS.map((edition) => [
      edition,
      {
        edition,
        capabilities: capabilities
          .filter((capability) => capability.editions.includes(edition))
          .map((capability) => capability.key),
      },
    ]),
  );
  const catalog = publicCatalog(capabilities, manifests);
  const publicManifestMap = publicManifests(manifests);
  const version = packageVersion();
  const metadata = {
    name: PACKAGE_NAME,
    version,
    description: 'Public AlphaCI capability keys, maturity, pack applicability, and dependencies.',
    main: 'index.js',
    types: 'index.d.ts',
    exports: {
      '.': {
        types: './index.d.ts',
        require: './index.js',
        default: './index.js',
      },
    },
    files: ['catalog.json', 'manifests.json', 'index.js', 'index.d.ts', PROVENANCE_FILE],
    license: 'UNLICENSED',
  };
  const catalogJson = `${JSON.stringify(catalog, null, 2)}\n`;
  const manifestsJson = `${JSON.stringify(publicManifestMap, null, 2)}\n`;
  const indexJs = `/* Generated from src/kernel/composition/catalog.source.json. */
/* Package integrity is recorded in provenance.json; do not edit this file by hand. */
/* eslint-disable @typescript-eslint/no-require-imports */
'use strict';

const catalog = require('./catalog.json');
const manifests = require('./manifests.json');
const { version } = require('./package.json');

module.exports = Object.freeze({
  version,
  catalog: Object.freeze(catalog),
  manifests: Object.freeze(manifests),
});
`;
  const packageFiles = {
    'package.json': `${JSON.stringify(metadata, null, 2)}\n`,
    'catalog.json': catalogJson,
    'index.d.ts': declaration(catalog),
    'index.js': indexJs,
    'manifests.json': manifestsJson,
  };
  const provenance = createProvenance({
    packageVersion: version,
    source,
    packageFiles,
  });

  return {
    version,
    metadata,
    catalog,
    manifests: publicManifestMap,
    indexJs,
    indexDts: packageFiles['index.d.ts'],
    packageFiles,
    provenance,
  };
}

function writePackage() {
  const output = buildPackage();
  fs.mkdirSync(PACKAGE_DIR, { recursive: true });
  for (const [file, contents] of Object.entries({
    ...output.packageFiles,
    [PROVENANCE_FILE]: `${JSON.stringify(output.provenance, null, 2)}\n`,
  })) {
    fs.writeFileSync(path.join(PACKAGE_DIR, file), contents, 'utf8');
  }
  console.log(
    `Packaged ${output.catalog.length} capability records as ${PACKAGE_NAME}@${output.version} (${output.provenance.artifactDigest}).`,
  );
}

if (require.main === module) writePackage();

module.exports = {
  DEFAULT_VERSION,
  EDITIONS,
  CANONICAL_PACKAGE_FILES,
  PACKAGE_DIR,
  PACKAGE_NAME,
  buildPackage,
  publicCatalog,
  publicManifests,
};
